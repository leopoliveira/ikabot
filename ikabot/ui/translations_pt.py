def get_building_emote(name: str) -> str:
    """Retorna o emoji/emote correspondente ao edifício."""
    if not name:
        return "🏗️"
    clean_name = name.split()[0] if " " in name else name
    return BUILDING_EMOTES.get(name, BUILDING_EMOTES.get(clean_name, "🏛️"))


def translate_building(name: str, with_emote: bool = True) -> str:
    """Traduz o nome do edifício incluindo emote correspondente."""
    if not name:
        return "🏗️ Terreno Vazio" if with_emote else "Terreno Vazio"
    clean_name = name.split()[0] if " " in name else name
    title = BUILDING_TRANSLATIONS.get(name, BUILDING_TRANSLATIONS.get(clean_name, name.capitalize()))
    if with_emote:
        emote = get_building_emote(name)
        return f"{emote} {title}"
    return title


def translate_action(action_name: str) -> str:
    """Traduz o nome da ação/processo incluindo emote."""
    return ACTION_NAMES.get(action_name, f"⚡ {action_name}")


def translate_resource(res_type) -> str:
    """Traduz o código ou nome do recurso."""
    return RESOURCE_NAMES.get(res_type, str(res_type))


def get_resource_icon(res_type) -> str:
    """Retorna o emoji/ícone para o recurso."""
    return RESOURCE_ICONS.get(res_type, "📦")
